#!/usr/bin/env python3
"""
Reels Publisher — DEVOPSRAIZ
============================

Publica vídeos no Instagram como Reels usando a Meta Graph API (v21.0).

Fluxo:
  1. Recebe caminho local do MP4 (ou gera via HeyGen)
  2. Faz upload do MP4 pra um storage público (GitHub Releases por padrão,
     também suporta Cloudflare R2/S3)
  3. Chama POST /{ig_user}/media com media_type=REELS e video_url
  4. Faz polling até container ficar FINISHED
  5. POST /{ig_user}/media_publish

Uso:
    # Publica o Reel do dia atual (gera vídeo via HeyGen + publica)
    python reels_publisher.py auto --today

    # Publica um Reel específico do calendário
    python reels_publisher.py auto --day 3

    # Pula a geração (MP4 já existe em ../videos_mp4/reel-dia-NN.mp4)
    python reels_publisher.py publish --day 3

    # Só gera o vídeo (não publica)
    python reels_publisher.py generate --day 3
"""

